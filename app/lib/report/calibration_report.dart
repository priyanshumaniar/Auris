import 'dart:typed_data';

import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../core/audiometry/audiometry.dart';
import '../core/audiometry/calibration.dart';
import '../data/calibration_history.dart';
import 'pdf_report.dart';

/// Printable record of one calibration done on this device: who did it, when,
/// with which headphones and method, and what it did to each ear.
class CalibrationRecordReport {
  const CalibrationRecordReport({required this.event, required this.clinic});

  final CalibrationEvent event;
  final ClinicDetails clinic;

  static final _dateTime = DateFormat('d MMM yyyy, HH:mm');

  static const _ink = PdfColor.fromInt(0xFF1B2A32);
  static const _muted = PdfColor.fromInt(0xFF5A6B75);
  static const _rule = PdfColor.fromInt(0xFFCFD8DC);
  static const _rightEar = PdfColor.fromInt(0xFFD32F2F);
  static const _leftEar = PdfColor.fromInt(0xFF1976D2);
  static const _warnBg = PdfColor.fromInt(0xFFFFF4E5);
  static const _warnEdge = PdfColor.fromInt(0xFFE0A458);

  String get fileName =>
      'Auris_calibration_${DateFormat('yyyy-MM-dd_HHmm').format(event.performedAt)}.pdf';

  Future<Uint8List> build({bool compress = true}) async {
    final doc = pw.Document(
      title: 'Calibration record ${_dateTime.format(event.performedAt)}',
      author: event.performedBy,
      creator: 'Auris',
      subject: 'Device calibration record',
      theme: await AudiogramReport.sharedTheme(),
      compress: compress,
    );

    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.fromLTRB(36, 34, 36, 40),
        header: (context) =>
            context.pageNumber == 1 ? _header() : pw.SizedBox(),
        footer: _footer,
        build: (context) => [
          pw.SizedBox(height: 12),
          _facts(),
          pw.SizedBox(height: 16),
          _title('What was done to each ear'),
          pw.SizedBox(height: 6),
          _earTable(),
          if (event.imbalanceDb != null) ...[
            pw.SizedBox(height: 8),
            pw.Text(
              'Left/right difference after calibration: '
              '${event.imbalanceDb!.toStringAsFixed(1)} dB'
              '${event.imbalanceAccepted ? ' (above the 10 dB warning level; saved after the user confirmed)' : ''}.',
              style: pw.TextStyle(
                fontSize: 9.5,
                color: event.imbalanceAccepted ? _warnEdge : _muted,
              ),
            ),
          ],
          pw.SizedBox(height: 16),
          ..._notes(),
        ],
      ),
    );
    return doc.save();
  }

  pw.Widget _header() => pw.Column(
    children: [
      pw.Row(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Expanded(
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text(
                  clinic.name,
                  style: const pw.TextStyle(
                    fontSize: 16,
                    fontWeight: pw.FontWeight.bold,
                    color: _ink,
                  ),
                ),
                if (clinic.address != null)
                  pw.Text(
                    clinic.address!,
                    style: const pw.TextStyle(fontSize: 9, color: _muted),
                  ),
                if (clinic.phone != null)
                  pw.Text(
                    clinic.phone!,
                    style: const pw.TextStyle(fontSize: 9, color: _muted),
                  ),
              ],
            ),
          ),
          pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.end,
            children: [
              pw.Text(
                'DEVICE CALIBRATION RECORD',
                style: const pw.TextStyle(
                  fontSize: 11,
                  fontWeight: pw.FontWeight.bold,
                  letterSpacing: 1.1,
                  color: _muted,
                ),
              ),
              pw.Text(
                event.isReset ? 'Calibration reset' : 'Air conduction',
                style: const pw.TextStyle(fontSize: 9, color: _muted),
              ),
            ],
          ),
        ],
      ),
      pw.SizedBox(height: 8),
      pw.Divider(color: _rule, thickness: 1, height: 1),
    ],
  );

  pw.Widget _footer(pw.Context context) => pw.Column(
    children: [
      pw.Divider(color: _rule, thickness: 0.5, height: 1),
      pw.SizedBox(height: 4),
      pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text(
            'Calibrated by ${event.performedBy}',
            style: const pw.TextStyle(fontSize: 8, color: _muted),
          ),
          pw.Text(
            'Generated by Auris - not a certified medical device',
            style: const pw.TextStyle(fontSize: 8, color: _muted),
          ),
          pw.Text(
            'Page ${context.pageNumber} of ${context.pagesCount}',
            style: const pw.TextStyle(fontSize: 8, color: _muted),
          ),
        ],
      ),
    ],
  );

  pw.Widget _facts() {
    final fields = <(String, String)>[
      ('Date and time', _dateTime.format(event.performedAt)),
      ('Performed by', event.performedBy),
      // A reset stores the default profile, whose headphone name means
      // nothing here.
      if (!event.isReset) ('Headphones', event.profile.transducerName),
      if (!event.isReset) ('Ears', event.earChoice.label),
      if (!event.isReset) ('Method', event.method.label),
      ('Device status after', _statusAfter()),
    ];
    return pw.Inseparable(
      child: pw.Container(
        padding: const pw.EdgeInsets.all(10),
        decoration: pw.BoxDecoration(
          border: pw.Border.all(color: _rule, width: 0.8),
          borderRadius: pw.BorderRadius.circular(4),
        ),
        child: pw.Wrap(
          spacing: 26,
          runSpacing: 8,
          children: [
            for (final (label, value) in fields)
              pw.SizedBox(
                width: 220,
                child: pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      label.toUpperCase(),
                      style: const pw.TextStyle(
                        fontSize: 7,
                        letterSpacing: 0.6,
                        fontWeight: pw.FontWeight.bold,
                        color: _muted,
                      ),
                    ),
                    pw.Text(
                      value,
                      style: const pw.TextStyle(fontSize: 10.5, color: _ink),
                    ),
                  ],
                ),
              ),
          ],
        ),
      ),
    );
  }

  String _statusAfter() => switch (event.profile.method) {
    CalibrationMethod.soundLevelMeter => 'Calibrated (sound level meter)',
    CalibrationMethod.biological => 'Roughly calibrated (human listener)',
    CalibrationMethod.none =>
      event.profile.hasAnyCalibration
          ? 'Partly calibrated (one ear uncalibrated)'
          : 'Not calibrated',
  };

  String _db(double? v) =>
      v == null ? '-' : '${v >= 0 ? '+' : ''}${v.toStringAsFixed(1)} dB';

  pw.Widget _earTable() {
    pw.Widget cell(String text, {bool bold = false, PdfColor color = _ink}) =>
        pw.Padding(
          padding: const pw.EdgeInsets.symmetric(vertical: 5, horizontal: 5),
          child: pw.Text(
            text,
            style: pw.TextStyle(
              fontSize: bold ? 9 : 9.5,
              fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal,
              color: color,
            ),
          ),
        );

    pw.TableRow row(Ear ear, PdfColor color) {
      final r = event.recordFor(ear);
      return pw.TableRow(
        children: [
          cell('${ear.label} (${ear.marker})', color: color),
          cell(r.action.label),
          cell(r.methodAfter.label),
          cell(_db(r.correctionDb)),
          // From the stored profile, so it includes corrections made by
          // calibrations saved before per-ear calibration existed.
          cell(_db(event.isReset ? 0 : event.profile.totalCorrectionDb(ear))),
        ],
      );
    }

    return pw.Table(
      border: pw.TableBorder.all(color: _rule, width: 0.6),
      columnWidths: const {
        0: pw.FlexColumnWidth(1.1),
        1: pw.FlexColumnWidth(1.6),
        2: pw.FlexColumnWidth(1.4),
        3: pw.FlexColumnWidth(1.2),
        4: pw.FlexColumnWidth(1.2),
      },
      children: [
        pw.TableRow(
          decoration: const pw.BoxDecoration(
            color: PdfColor.fromInt(0xFFF2F5F7),
          ),
          children: [
            cell('Ear', bold: true),
            cell('This time', bold: true),
            cell('Method now', bold: true),
            cell('Change applied', bold: true),
            cell('Total correction now', bold: true),
          ],
        ),
        row(Ear.right, _rightEar),
        row(Ear.left, _leftEar),
      ],
    );
  }

  List<pw.Widget> _notes() {
    final notes = <(String, String, bool)>[];
    if (event.profile.usesHumanListener) {
      notes.add((
        'CALIBRATED WITH A HUMAN LISTENER - NOT A STANDARD CALIBRATION',
        kHumanCalibrationWarning +
            (event.listenerConfirmedEqualEars
                ? ' The person calibrating confirmed the listener has no '
                      'known hearing difference between their ears.'
                : ''),
        true,
      ));
    }
    for (final ear in Ear.values) {
      if (event.recordFor(ear).action == EarAction.copied) {
        notes.add((
          '${ear.label.toUpperCase()} EAR COPIED, NOT MEASURED',
          'The ${ear.label.toLowerCase()} ear was given the same correction '
              'as the ${ear.other.label.toLowerCase()} ear. If the two sides '
              'of the headphones are not equally loud, results for this ear '
              'will be off by that difference.',
          true,
        ));
      }
      if (!event.isReset && !event.profile.ear(ear).hasCalibration) {
        notes.add((
          '${ear.label.toUpperCase()} EAR NOT CALIBRATED',
          'Tests on the ${ear.label.toLowerCase()} ear will be marked as '
              'screening only until it is calibrated.',
          true,
        ));
      }
    }
    if (!event.isReset) {
      notes.add((
        'VALIDITY',
        'This calibration is valid only for ${event.profile.transducerName} on '
            'this device at the volume setting used during calibration. Repeat '
            'it after changing the headphones, the device or the volume, and as '
            'a routine check every few months.',
        false,
      ));
    }

    return [
      for (final (heading, body, warn) in notes) ...[
        // Inseparable: a box that does not fit must move to the next page
        // whole, not be drawn empty at the foot of this one.
        pw.Inseparable(
          child: pw.Container(
            width: double.infinity,
            padding: const pw.EdgeInsets.all(10),
            decoration: pw.BoxDecoration(
              color: warn ? _warnBg : PdfColors.grey100,
              border: pw.Border.all(
                color: warn ? _warnEdge : _rule,
                width: 0.8,
              ),
              borderRadius: pw.BorderRadius.circular(4),
            ),
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text(
                  heading,
                  style: pw.TextStyle(
                    fontSize: 9,
                    fontWeight: pw.FontWeight.bold,
                    letterSpacing: 0.4,
                    color: warn ? _warnEdge : _muted,
                  ),
                ),
                pw.SizedBox(height: 4),
                pw.Text(
                  body,
                  style: const pw.TextStyle(
                    fontSize: 9,
                    color: _ink,
                    lineSpacing: 1.5,
                  ),
                ),
              ],
            ),
          ),
        ),
        pw.SizedBox(height: 8),
      ],
    ];
  }

  pw.Widget _title(String text) => pw.Text(
    text.toUpperCase(),
    style: const pw.TextStyle(
      fontSize: 9,
      letterSpacing: 0.8,
      fontWeight: pw.FontWeight.bold,
      color: _muted,
    ),
  );
}
